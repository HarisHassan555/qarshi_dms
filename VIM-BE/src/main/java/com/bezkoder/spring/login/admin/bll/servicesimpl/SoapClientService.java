    private void addlogEntry(SOAPMessage soapMessage, String xmlPayload, String msgType, SlsTblSaleOrder order, String procurementNo) {

        EntityManager entityManager = getEntityManager();
        int orderId = 0;

        if (procurementNo == null || procurementNo.isEmpty()) {
            procurementNo = null;
        }

        if (order == null) {
            orderId = 0;
        } else {
            orderId = order.getSerSaleOrderId();
        }

        try {
            entityManager.getTransaction().begin();

            // Create the audit log entry
            AuditSlsTblSes auditSlsTblSes = new AuditSlsTblSes();
            auditSlsTblSes.setTxtRequest(getSoapMessageAsString(soapMessage));
            auditSlsTblSes.setTxtResponse(String.valueOf(xmlPayload));
            auditSlsTblSes.setSerSaleOrderId(orderId);
            auditSlsTblSes.setProcurementNo(procurementNo);
            auditSlsTblSes.setMsgType(msgType);
            auditSlsTblSes.setDteCreateddate(commonService.getCurrentTimeStamp_new());
            auditSlsTblSes.setSerCreatedUserId(commonService.getCurrentLoggedInUser());

            // Persist the audit log entry
            entityManager.persist(auditSlsTblSes);

            // Commit the transaction
            entityManager.getTransaction().commit();

        } catch (Exception e) {
            // Rollback the transaction if an error occurs
            if (entityManager.getTransaction().isActive()) {
                entityManager.getTransaction().rollback();
            }
            log.error(e.getMessage(), e);

        } finally {
            // Ensure entityManager is always closed
            if (entityManager.isOpen()) {
                entityManager.close();
            }
        }
    }


