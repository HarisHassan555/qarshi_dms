    public List<SlsTblSaleOrder> readSOAPResponseSES(SOAPRequestResponseWrapper soapMessage, SlsTblSaleOrder order) throws Exception {

        String xmlPayload = null;
        try {
            TransformerFactory transformerFactory = TransformerFactory.newInstance();
            Transformer transformer = transformerFactory.newTransformer();
            SOAPBody soapBody = soapMessage.getSoapResponse().getSOAPBody();
            Source sourceContent = soapMessage.getSoapResponse().getSOAPPart().getContent();
            StringWriter writer = new StringWriter();
            transformer.transform(sourceContent, new StreamResult(writer));
             xmlPayload = writer.toString();

            System.out.println("\nRaw Response SOAP Message = ");
            System.out.println(xmlPayload);
            addlogEntry(soapMessage.getSoapRequest(),xmlPayload,"SES",order,null);
            List<SlsTblSaleOrder> slsTblSaleOrder = parseSOAPResponseSES(xmlPayload);

            // Return the parsed list of deals
            return slsTblSaleOrder;

        } catch (TransformerException e) {
            addlogEntry(soapMessage.getSoapRequest(),xmlPayload,"SES",order,null);
            throw new Exception("Error during transformation of SOAP response", e);
        } catch (SOAPException e) {
            addlogEntry(soapMessage.getSoapRequest(), xmlPayload,"SES",order,null);
            throw new Exception("Error extracting content from SOAP message", e);
        } catch (Exception e) {
            addlogEntry(soapMessage.getSoapRequest(),xmlPayload,"SES",order,null);
            throw new Exception("Unexpected error while processing SOAP response", e);
        }
    }


