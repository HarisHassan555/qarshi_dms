    private SOAPMessage createSOAPRequest(String erDate) throws Exception {
        // Create the SOAP message
        MessageFactory messageFactory = MessageFactory.newInstance();
        SOAPMessage soapMessage = messageFactory.createMessage();
        MimeHeaders hd = soapMessage.getMimeHeaders();
        String authorization = Base64.getEncoder().encodeToString((username + ":" + password).getBytes());
        hd.addHeader("Authorization", "Basic " + authorization);
        hd.addHeader("SOAPAction", soapAction);
        SOAPPart soapPart = soapMessage.getSOAPPart();
        SOAPEnvelope soapEnvelope = soapPart.getEnvelope();
        soapEnvelope.addNamespaceDeclaration("urn", "urn:sap-com:document:sap:soap:functions:mc-style");

        SOAPBody soapBody = soapEnvelope.getBody();
        ZkfEInvoiceWebService customer = new ZkfEInvoiceWebService();
        JAXBContext jaxbContext = JAXBContext.newInstance(ZkfEInvoiceWebService.class);
        Marshaller jaxbMarshaller = jaxbContext.createMarshaller();
        jaxbMarshaller.setProperty(Marshaller.JAXB_FORMATTED_OUTPUT, true);
        jaxbMarshaller.setProperty(Marshaller.JAXB_ENCODING, "UTF-8");
        customer.setErdat(erDate);
        jaxbMarshaller.marshal(customer, soapBody);

        soapMessage.saveChanges();
        soapMessage.setProperty(SOAPMessage.WRITE_XML_DECLARATION, "true");
        soapMessage.setProperty(SOAPMessage.CHARACTER_SET_ENCODING, "UTF-8");
        System.out.println("Request SOAP Message = ");
        soapMessage.writeTo(System.out);

        return soapMessage;
    }


